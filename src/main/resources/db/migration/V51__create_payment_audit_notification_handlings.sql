-- Administrator handling does not change notification delivery or existing data.
CREATE TABLE payment_audit_notification_handling_histories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT NOT NULL REFERENCES payment_audit_notifications (id) ON DELETE RESTRICT,
    from_status VARCHAR(24) NOT NULL,
    to_status VARCHAR(24) NOT NULL,
    actor_user_id BIGINT NOT NULL,
    actor_username VARCHAR(100) NOT NULL,
    comment VARCHAR(1000),
    event_id UUID NOT NULL UNIQUE,
    changed_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_audit_notification_handling_history_status UNIQUE (id, notification_id, to_status),
    CONSTRAINT chk_audit_notification_handling_history_status CHECK (
        from_status IN ('UNREVIEWED', 'IN_PROGRESS', 'RESOLVED')
        AND to_status IN ('UNREVIEWED', 'IN_PROGRESS', 'RESOLVED')
        AND from_status <> to_status
    ),
    -- Fixed whitespace set: U+0009..000D, U+0020, U+0085, U+00A0,
    -- U+1680, U+2000..200B, U+2028, U+2029, U+202F, U+205F, U+3000.
    -- This includes Unicode White_Space plus the explicitly required U+200B.
    -- translate removes exactly these code points, without locale classification
    -- or regex ranges. U& uses four hexadecimal digits per BMP code point.
    -- Future Java validation must use the same explicit set with codePoints();
    -- do not substitute trim(), isBlank(), Character.isWhitespace() or regex \s.
    CONSTRAINT chk_audit_notification_handling_history_comment CHECK (
        (from_status <> 'RESOLVED' AND to_status <> 'RESOLVED')
        OR (comment IS NOT NULL AND char_length(translate(comment,
            U&'\0009\000A\000B\000C\000D\0020\0085\00A0\1680\2000\2001\2002\2003\2004\2005\2006\2007\2008\2009\200A\200B\2028\2029\202F\205F\3000',
            '')) > 0)
    ),
    -- UTF8 character count is the Unicode code-point count, including whitespace.
    -- Java equivalent: comment.codePointCount(0, comment.length()) <= 1000.
    -- No trimming or normalization precedes this length check.
    CONSTRAINT chk_audit_notification_handling_history_comment_length CHECK (
        comment IS NULL OR char_length(comment) <= 1000
    )
);
CREATE INDEX idx_audit_notification_handling_history_time
    ON payment_audit_notification_handling_histories (notification_id, changed_at, id);

CREATE TABLE payment_audit_notification_handlings (
    notification_id BIGINT PRIMARY KEY REFERENCES payment_audit_notifications (id) ON DELETE RESTRICT,
    handling_status VARCHAR(24) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    last_resolved_history_id BIGINT,
    -- Database-only discriminator ensures the pointer targets a RESOLVED transition.
    last_resolved_history_status VARCHAR(24) GENERATED ALWAYS AS (
        CASE WHEN last_resolved_history_id IS NOT NULL THEN 'RESOLVED'::VARCHAR(24) END
    ) STORED,
    CONSTRAINT chk_audit_notification_handling_status CHECK (
        handling_status IN ('UNREVIEWED', 'IN_PROGRESS', 'RESOLVED')
    ),
    CONSTRAINT chk_audit_notification_handling_version CHECK (version >= 0),
    CONSTRAINT chk_audit_notification_handling_times CHECK (updated_at >= created_at),
    CONSTRAINT chk_audit_notification_handling_resolved CHECK (
        handling_status <> 'RESOLVED' OR last_resolved_history_id IS NOT NULL
    ),
    CONSTRAINT fk_audit_notification_handling_last_resolved FOREIGN KEY (
        last_resolved_history_id, notification_id, last_resolved_history_status
    ) REFERENCES payment_audit_notification_handling_histories (id, notification_id, to_status) ON DELETE RESTRICT
);
CREATE INDEX idx_audit_notification_handling_status
    ON payment_audit_notification_handlings (handling_status, notification_id);

CREATE TABLE payment_audit_notification_handling_history_unknowns (
    history_id BIGINT NOT NULL,
    notification_id BIGINT NOT NULL,
    attempt_no INTEGER NOT NULL,
    history_to_status VARCHAR(24) GENERATED ALWAYS AS ('RESOLVED'::VARCHAR(24)) STORED,
    PRIMARY KEY (history_id, attempt_no),
    CONSTRAINT fk_audit_notification_handling_unknown_history FOREIGN KEY (history_id, notification_id, history_to_status)
        REFERENCES payment_audit_notification_handling_histories (id, notification_id, to_status) ON DELETE RESTRICT,
    CONSTRAINT fk_audit_notification_handling_unknown_attempt FOREIGN KEY (notification_id, attempt_no)
        REFERENCES payment_audit_notification_attempts (notification_id, attempt_no) ON DELETE RESTRICT
);
-- UNKNOWN membership is checked by the future handling service while holding
-- the notification parent lock; the FK already requires a RESOLVED history.
CREATE INDEX idx_audit_notification_unknown_attempt
    ON payment_audit_notification_attempts (notification_id, attempt_no) WHERE result = 'UNKNOWN';
