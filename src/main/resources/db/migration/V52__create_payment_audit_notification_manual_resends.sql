-- Independent manual delivery; V50/V51 notification and handling rows are untouched.
CREATE TABLE payment_audit_notification_manual_resends (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT NOT NULL REFERENCES payment_audit_notifications(id) ON DELETE RESTRICT,
    request_no INTEGER NOT NULL CHECK (request_no IN (1, 2)),
    request_nonce UUID NOT NULL UNIQUE,
    actor_user_id BIGINT NOT NULL CHECK (actor_user_id > 0),
    actor_username VARCHAR(100) NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    risk_acknowledged BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(24) NOT NULL,
    result_reason_code VARCHAR(40),
    claim_token UUID UNIQUE,
    claimed_by UUID,
    lease_until TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    requested_at TIMESTAMPTZ NOT NULL,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    CONSTRAINT uq_manual_resends_number UNIQUE (notification_id, request_no),
    CONSTRAINT uq_manual_resends_notification UNIQUE (id, notification_id),
    CONSTRAINT chk_manual_resends_status CHECK (status IN
        ('PENDING', 'CLAIMED', 'SENDING', 'SENT', 'FAILED', 'UNKNOWN', 'CANCELLED')),
    -- Identical to Feature117: no trimming/normalization, 1000 code points,
    -- Unicode White_Space plus U+200B (26 explicitly enumerated code points).
    CONSTRAINT chk_manual_resends_reason CHECK (char_length(reason) <= 1000 AND
        char_length(translate(reason,
            U&'\0009\000A\000B\000C\000D\0020\0085\00A0\1680\2000\2001\2002\2003\2004\2005\2006\2007\2008\2009\200A\200B\2028\2029\202F\205F\3000', '')) > 0),
    CONSTRAINT chk_manual_resends_claim CHECK (
        (status IN ('CLAIMED', 'SENDING') AND claim_token IS NOT NULL AND claimed_by IS NOT NULL AND lease_until IS NOT NULL)
        OR (status NOT IN ('CLAIMED', 'SENDING') AND claim_token IS NULL AND claimed_by IS NULL AND lease_until IS NULL)),
    CONSTRAINT chk_manual_resends_started CHECK (
        (status IN ('SENDING', 'SENT', 'FAILED', 'UNKNOWN') AND started_at IS NOT NULL)
        OR (status IN ('PENDING', 'CLAIMED', 'CANCELLED') AND started_at IS NULL)),
    CONSTRAINT chk_manual_resends_finished CHECK (
        (status IN ('SENT', 'FAILED', 'UNKNOWN', 'CANCELLED') AND finished_at IS NOT NULL)
        OR (status IN ('PENDING', 'CLAIMED', 'SENDING') AND finished_at IS NULL)),
    CONSTRAINT chk_manual_resends_result_reason CHECK (
        (status IN ('PENDING', 'CLAIMED', 'SENDING', 'SENT') AND result_reason_code IS NULL)
        OR (status IN ('FAILED', 'UNKNOWN') AND result_reason_code IS NOT NULL AND result_reason_code IN
            ('SMTP_CONNECT_FAILED', 'SMTP_REJECTED', 'SMTP_SEND_FAILED', 'SEND_DEADLINE_EXCEEDED', 'CLAIM_LOST'))
        OR (status = 'CANCELLED' AND result_reason_code IS NOT NULL AND result_reason_code IN
            ('RESOLVED', 'NO_VALID_RECIPIENTS', 'HANDLING_RESOLVED', 'RESEND_PROHIBITED', 'NOTIFICATION_DISABLED'))),
    CONSTRAINT chk_manual_resends_times CHECK (
        (started_at IS NULL OR started_at >= requested_at)
        AND (finished_at IS NULL OR finished_at >= COALESCE(started_at, requested_at)))
);
CREATE UNIQUE INDEX uq_manual_resends_active ON payment_audit_notification_manual_resends(notification_id)
    WHERE status IN ('PENDING', 'CLAIMED', 'SENDING');
CREATE INDEX idx_manual_resends_history ON payment_audit_notification_manual_resends(notification_id, requested_at, id);
CREATE INDEX idx_manual_resends_pending ON payment_audit_notification_manual_resends(requested_at, id) WHERE status = 'PENDING';
CREATE INDEX idx_manual_resends_lease ON payment_audit_notification_manual_resends(lease_until, id) WHERE status IN ('CLAIMED', 'SENDING');
-- The 30-minute interval and second-request risk acknowledgement are checked by
-- the future acceptance service under the original notification row lock.

CREATE TABLE payment_audit_notification_manual_resend_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manual_resend_id BIGINT NOT NULL UNIQUE,
    notification_id BIGINT NOT NULL,
    result VARCHAR(24) NOT NULL,
    claim_token UUID NOT NULL UNIQUE,
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    result_reason_code VARCHAR(40),
    recipients TEXT[] NOT NULL,
    subject TEXT NOT NULL,
    body TEXT NOT NULL,
    CONSTRAINT fk_manual_attempt_request FOREIGN KEY (manual_resend_id, notification_id)
        REFERENCES payment_audit_notification_manual_resends(id, notification_id) ON DELETE RESTRICT,
    CONSTRAINT uq_manual_attempt_notification_result UNIQUE (id, notification_id, result),
    CONSTRAINT chk_manual_attempt_result CHECK (result IN ('IN_PROGRESS', 'SUCCESS', 'FAILURE', 'UNKNOWN')),
    CONSTRAINT chk_manual_attempt_finished CHECK (
        (result = 'IN_PROGRESS' AND finished_at IS NULL AND result_reason_code IS NULL)
        OR (result = 'SUCCESS' AND finished_at IS NOT NULL AND result_reason_code IS NULL)
        OR (result IN ('FAILURE', 'UNKNOWN') AND finished_at IS NOT NULL AND result_reason_code IS NOT NULL)),
    CONSTRAINT chk_manual_attempt_reason CHECK (result_reason_code IS NULL OR result_reason_code IN
        ('SMTP_CONNECT_FAILED', 'SMTP_REJECTED', 'SMTP_SEND_FAILED', 'SEND_DEADLINE_EXCEEDED', 'CLAIM_LOST')),
    CONSTRAINT chk_manual_attempt_times CHECK (finished_at IS NULL OR finished_at >= started_at),
    CONSTRAINT chk_manual_attempt_recipients CHECK (
        array_ndims(recipients) = 1 AND cardinality(recipients) BETWEEN 1 AND 20
        AND array_position(recipients, NULL) IS NULL AND array_position(recipients, '') IS NULL)
);
CREATE INDEX idx_manual_attempt_unknown ON payment_audit_notification_manual_resend_attempts(notification_id, id) WHERE result = 'UNKNOWN';

CREATE TABLE payment_audit_notification_handling_history_manual_unknowns (
    history_id BIGINT NOT NULL,
    manual_attempt_id BIGINT NOT NULL,
    notification_id BIGINT NOT NULL,
    history_to_status VARCHAR(24) GENERATED ALWAYS AS ('RESOLVED'::VARCHAR(24)) STORED,
    attempt_result VARCHAR(24) GENERATED ALWAYS AS ('UNKNOWN'::VARCHAR(24)) STORED,
    PRIMARY KEY (history_id, manual_attempt_id),
    CONSTRAINT fk_manual_unknown_history FOREIGN KEY (history_id, notification_id, history_to_status)
        REFERENCES payment_audit_notification_handling_histories(id, notification_id, to_status) ON DELETE RESTRICT,
    CONSTRAINT fk_manual_unknown_attempt FOREIGN KEY (manual_attempt_id, notification_id, attempt_result)
        REFERENCES payment_audit_notification_manual_resend_attempts(id, notification_id, result) ON DELETE RESTRICT
);
CREATE INDEX idx_manual_unknown_attempt ON payment_audit_notification_handling_history_manual_unknowns(manual_attempt_id);

-- Validate the final transaction state, so ORM flush ordering may update request
-- and attempt separately. No FK cycle and no writes to the original notification.
-- Future writers must lock notification -> manual request -> attempt in that order.
CREATE FUNCTION check_manual_resend_attempt_consistency() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    request_id BIGINT;
    request_row payment_audit_notification_manual_resends%ROWTYPE;
    attempt_row payment_audit_notification_manual_resend_attempts%ROWTYPE;
    expected_result VARCHAR(24);
BEGIN
    IF TG_TABLE_NAME = 'payment_audit_notification_manual_resends' THEN
        request_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END;
    ELSE
        request_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.manual_resend_id ELSE NEW.manual_resend_id END;
        IF TG_OP = 'UPDATE' AND OLD.manual_resend_id <> NEW.manual_resend_id THEN
            RAISE EXCEPTION 'Manual attempt request identity is immutable' USING ERRCODE = '23514';
        END IF;
    END IF;
    SELECT * INTO request_row FROM payment_audit_notification_manual_resends WHERE id = request_id;
    IF NOT FOUND THEN RETURN NULL; END IF;
    SELECT * INTO attempt_row FROM payment_audit_notification_manual_resend_attempts WHERE manual_resend_id = request_id;
    IF request_row.status IN ('PENDING', 'CLAIMED', 'CANCELLED') THEN
        IF FOUND THEN RAISE EXCEPTION 'Pre-send manual request must not have an attempt' USING ERRCODE = '23514'; END IF;
    ELSE
        IF NOT FOUND THEN RAISE EXCEPTION 'Started manual request requires an attempt' USING ERRCODE = '23514'; END IF;
        expected_result := CASE request_row.status WHEN 'SENDING' THEN 'IN_PROGRESS' WHEN 'SENT' THEN 'SUCCESS'
            WHEN 'FAILED' THEN 'FAILURE' WHEN 'UNKNOWN' THEN 'UNKNOWN' END;
        IF attempt_row.result <> expected_result OR attempt_row.result_reason_code IS DISTINCT FROM request_row.result_reason_code
            OR (request_row.status = 'SENDING' AND attempt_row.claim_token <> request_row.claim_token) THEN
            RAISE EXCEPTION 'Manual request and attempt results must agree' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER chk_manual_request_attempt_consistency
    AFTER INSERT OR UPDATE OR DELETE ON payment_audit_notification_manual_resends
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_manual_resend_attempt_consistency();
CREATE CONSTRAINT TRIGGER chk_manual_attempt_request_consistency
    AFTER INSERT OR UPDATE OR DELETE ON payment_audit_notification_manual_resend_attempts
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_manual_resend_attempt_consistency();
