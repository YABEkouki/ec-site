CREATE TABLE order_change_financial_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id UUID NOT NULL,
    order_id BIGINT NOT NULL,
    payment_id BIGINT NOT NULL,
    transaction_id BIGINT NOT NULL UNIQUE,
    purpose VARCHAR(40) COLLATE "C" NOT NULL,
    request_kind VARCHAR(20) NOT NULL,
    transaction_type VARCHAR(30) NOT NULL,
    amount INTEGER NOT NULL CHECK(amount BETWEEN 50 AND 9999999),
    provider_flow_id VARCHAR(255),
    idempotency_key VARCHAR(100) COLLATE "C" NOT NULL UNIQUE CHECK(idempotency_key ~ '^[A-Za-z0-9_-]{1,100}$'),
    connection_id VARCHAR(100) NOT NULL CHECK(connection_id COLLATE "C" ~ '^[A-Za-z0-9_-]{1,100}$'),
    provider_account_ref VARCHAR(100) NOT NULL CHECK(provider_account_ref COLLATE "C" ~ '^[A-Za-z0-9_-]{1,100}$'),
    mode VARCHAR(10) NOT NULL CHECK(mode IN ('TEST','LIVE')),
    api_origin VARCHAR(255) NOT NULL CHECK(api_origin='https://api.pay.jp'),
    http_method VARCHAR(10) NOT NULL CHECK(http_method='POST'),
    api_path VARCHAR(512) NOT NULL,
    content_type VARCHAR(50) NOT NULL CHECK(content_type='application/json'),
    body_format_version SMALLINT NOT NULL CHECK(body_format_version=1),
    request_body BYTEA NOT NULL CHECK(octet_length(request_body) BETWEEN 1 AND 4096),
    fingerprint_version SMALLINT NOT NULL CHECK(fingerprint_version=1),
    request_fingerprint BYTEA NOT NULL CHECK(octet_length(request_fingerprint)=32),
    created_at TIMESTAMPTZ NOT NULL,
    replay_not_after TIMESTAMPTZ NOT NULL CHECK(replay_not_after>created_at AND replay_not_after<=created_at+interval '23 hours'),
    CONSTRAINT uq_change_request_purpose UNIQUE(operation_id,purpose),
    CONSTRAINT fk_change_request_operation FOREIGN KEY(operation_id,order_id) REFERENCES order_change_operations(id,order_id),
    CONSTRAINT fk_change_request_payment FOREIGN KEY(order_id,payment_id) REFERENCES payments(order_id,id),
    CONSTRAINT fk_change_request_transaction FOREIGN KEY(transaction_id,payment_id,operation_id,order_id,purpose,transaction_type,amount,idempotency_key)
        REFERENCES payment_transactions(id,payment_id,order_change_operation_id,order_change_order_id,purpose,transaction_type,amount,idempotency_key),
    CONSTRAINT ck_change_request_kind CHECK (
        (request_kind='CREATE' AND purpose='ORDER_CHANGE_AUTHORIZATION' AND transaction_type='AUTHORIZE'
            AND provider_flow_id IS NULL AND api_path='/v2/payment_flows')
        OR (request_kind IN ('OLD_CANCEL','NEW_ABORT') AND transaction_type='CANCEL' AND provider_flow_id IS NOT NULL
            AND provider_flow_id COLLATE "C" ~ '^pfw_[A-Za-z0-9_-]+$'
            AND api_path='/v2/payment_flows/'||provider_flow_id||'/cancel'
            AND ((request_kind='OLD_CANCEL' AND purpose='ORDER_CHANGE_OLD_AUTH_CANCEL')
                OR (request_kind='NEW_ABORT' AND purpose='ORDER_CHANGE_NEW_AUTH_ABORT')))
    )
);
CREATE INDEX idx_change_requests_payment ON order_change_financial_requests(payment_id);
CREATE FUNCTION reject_change_financial_request_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION USING ERRCODE='55000', MESSAGE='Order change financial requests are immutable';
END;
$$;
CREATE TRIGGER change_requests_no_mutation BEFORE UPDATE OR DELETE OR TRUNCATE ON order_change_financial_requests
    FOR EACH STATEMENT EXECUTE FUNCTION reject_change_financial_request_mutation();

-- An abort request is a durable decision to abandon this candidate. It cannot race a later switch.
-- Both writers serialize on the operation row; the store locks Order first.
CREATE FUNCTION enforce_change_request_role() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE op order_change_operations%ROWTYPE;
BEGIN
    SELECT * INTO STRICT op FROM order_change_operations WHERE id=NEW.operation_id FOR UPDATE;
    IF NEW.request_kind='OLD_CANCEL' THEN
        IF NEW.payment_id<>op.old_payment_id OR op.switch_decided_at IS NULL THEN
            RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Invalid old Cancel role or decision';
        END IF;
    ELSE
        IF op.new_payment_id IS NULL OR NEW.payment_id<>op.new_payment_id OR NEW.payment_id=op.old_payment_id THEN
            RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Invalid new Payment role';
        END IF;
        IF NEW.request_kind='NEW_ABORT' AND (op.switch_decided_at IS NOT NULL OR op.state NOT IN ('ABORTING','ABORT_UNKNOWN')) THEN
            RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Invalid abort decision';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER change_requests_role BEFORE INSERT ON order_change_financial_requests
    FOR EACH ROW EXECUTE FUNCTION enforce_change_request_role();
CREATE FUNCTION protect_change_request_roles() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS(SELECT 1 FROM order_change_financial_requests WHERE operation_id=OLD.id) AND
        (NEW.order_id IS DISTINCT FROM OLD.order_id OR NEW.new_payment_id IS DISTINCT FROM OLD.new_payment_id
         OR NEW.old_payment_id IS DISTINCT FROM OLD.old_payment_id OR NEW.after_amount IS DISTINCT FROM OLD.after_amount
         OR NEW.base_content_revision IS DISTINCT FROM OLD.base_content_revision) THEN
        RAISE EXCEPTION USING ERRCODE='55000', MESSAGE='Financial request roles are immutable';
    END IF;
    IF NEW.switch_decided_at IS NOT NULL AND EXISTS(SELECT 1 FROM order_change_financial_requests
        WHERE operation_id=OLD.id AND request_kind='NEW_ABORT') THEN
        RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Cannot switch an aborted authorization candidate';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER change_operation_financial_roles BEFORE UPDATE ON order_change_operations
    FOR EACH ROW EXECUTE FUNCTION protect_change_request_roles();
