-- Foundation only: no backfill, dispatch, recovery permission or existing-flow integration.
-- The redundant identity constraints support composite FKs without constraining status/completion.
ALTER TABLE payments ADD CONSTRAINT uq_payments_capture_identity
    UNIQUE (id, provider, payment_method, provider_payment_id);
ALTER TABLE payment_transactions ADD CONSTRAINT uq_transactions_capture_identity
    UNIQUE (id, payment_id, transaction_type, amount, order_content_revision, idempotency_key);

CREATE TABLE capture_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL,
    capture_transaction_id BIGINT NOT NULL UNIQUE,
    transaction_type VARCHAR(30) NOT NULL CHECK (transaction_type = 'CAPTURE'),
    provider VARCHAR(30) NOT NULL CHECK (provider = 'PAYJP'),
    payment_method VARCHAR(30) NOT NULL CHECK (payment_method = 'CARD'),
    provider_flow_id VARCHAR(255) NOT NULL CHECK (provider_flow_id COLLATE "C" ~ '^pfw_[A-Za-z0-9_-]+$'),
    connection_id VARCHAR(100) NOT NULL CHECK (connection_id COLLATE "C" ~ '^[A-Za-z0-9_-]+$'),
    provider_account_ref VARCHAR(100) NOT NULL CHECK (provider_account_ref COLLATE "C" ~ '^[A-Za-z0-9_-]+$'),
    mode VARCHAR(10) NOT NULL CHECK (mode IN ('TEST', 'LIVE')),
    api_origin VARCHAR(255) NOT NULL CHECK (api_origin = 'https://api.pay.jp'),
    http_method VARCHAR(10) NOT NULL CHECK (http_method = 'POST'),
    api_path VARCHAR(512) NOT NULL CHECK (api_path = '/v2/payment_flows/' || provider_flow_id || '/capture'),
    content_type VARCHAR(50) NOT NULL CHECK (content_type = 'application/json'),
    amount_to_capture INTEGER NOT NULL CHECK (amount_to_capture > 0),
    order_content_revision INTEGER NOT NULL CHECK (order_content_revision >= 0),
    idempotency_key VARCHAR(100) NOT NULL CHECK (idempotency_key COLLATE "C" ~ '^[A-Za-z0-9_-]+$'),
    body_format_version SMALLINT NOT NULL CHECK (body_format_version = 1),
    request_body BYTEA NOT NULL CHECK (
        request_body = convert_to('{"amount_to_capture":' || amount_to_capture::text || '}', 'UTF8')),
    fingerprint_version SMALLINT NOT NULL CHECK (fingerprint_version = 1),
    request_fingerprint BYTEA NOT NULL CHECK (octet_length(request_fingerprint) = 32),
    created_at TIMESTAMPTZ NOT NULL,
    replay_not_after TIMESTAMPTZ NOT NULL CHECK (
        replay_not_after > created_at AND replay_not_after <= created_at + INTERVAL '23 hours'),
    CONSTRAINT fk_capture_request_payment FOREIGN KEY (payment_id, provider, payment_method, provider_flow_id)
        REFERENCES payments (id, provider, payment_method, provider_payment_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_capture_request_transaction FOREIGN KEY (
        capture_transaction_id, payment_id, transaction_type, amount_to_capture, order_content_revision, idempotency_key)
        REFERENCES payment_transactions (id, payment_id, transaction_type, amount, order_content_revision, idempotency_key)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);
CREATE INDEX idx_capture_requests_payment ON capture_requests(payment_id);

CREATE FUNCTION reject_capture_request_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION USING ERRCODE = '55000', MESSAGE = 'Capture requests are immutable; separately approved DBA maintenance is required';
END;
$$;
-- Statement triggers reject even empty-table mutation. No application-controlled bypass exists.
CREATE TRIGGER capture_requests_no_update_delete BEFORE UPDATE OR DELETE ON capture_requests
    FOR EACH STATEMENT EXECUTE FUNCTION reject_capture_request_mutation();
CREATE TRIGGER capture_requests_no_truncate BEFORE TRUNCATE ON capture_requests
    FOR EACH STATEMENT EXECUTE FUNCTION reject_capture_request_mutation();
