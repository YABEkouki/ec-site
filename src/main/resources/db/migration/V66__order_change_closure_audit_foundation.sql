-- Persistence only: no observation, backfill, notification or financial state mutation.
-- Non-null audit targets must reference precisely the operation's NEW Payment.
ALTER TABLE order_change_operations ADD CONSTRAINT uq_change_audit_target UNIQUE(id,order_id,new_payment_id);

CREATE TABLE order_change_closure_runs (
    id UUID PRIMARY KEY,
    run_kind VARCHAR(24) NOT NULL CHECK(run_kind IN ('SCHEDULER','RECOVERY','MANUAL')),
    status VARCHAR(24) NOT NULL CHECK(status IN ('RUNNING','SUCCESS','PARTIAL_FAILURE','FAILED','UNKNOWN')),
    version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    heartbeat_at TIMESTAMPTZ NOT NULL,
    candidate_count INTEGER,
    processed_count INTEGER NOT NULL DEFAULT 0,
    closed_count INTEGER NOT NULL DEFAULT 0,
    retry_count INTEGER NOT NULL DEFAULT 0,
    conflict_count INTEGER NOT NULL DEFAULT 0,
    failure_count INTEGER NOT NULL DEFAULT 0,
    enabled_snapshot BOOLEAN NOT NULL,
    duration_ms BIGINT,
    created_at TIMESTAMPTZ NOT NULL,
    CHECK(heartbeat_at>=started_at AND (finished_at IS NULL OR finished_at>=heartbeat_at)),
    CHECK((status='RUNNING' AND finished_at IS NULL AND duration_ms IS NULL) OR
          (status<>'RUNNING' AND finished_at IS NOT NULL AND duration_ms IS NOT NULL AND duration_ms>=0)),
    -- Stored duration is the wall-clock interval in whole milliseconds, not a financial outcome.
    CHECK(duration_ms IS NULL OR duration_ms=FLOOR(EXTRACT(EPOCH FROM (finished_at-started_at))*1000)),
    CHECK((candidate_count IS NULL OR candidate_count>=0) AND processed_count>=0 AND closed_count>=0
          AND retry_count>=0 AND conflict_count>=0 AND failure_count>=0),
    CHECK((candidate_count IS NULL AND processed_count=0) OR (candidate_count IS NOT NULL AND processed_count<=candidate_count)),
    CHECK(closed_count::BIGINT+retry_count+conflict_count+failure_count<=processed_count),
    CHECK(status<>'SUCCESS' OR (candidate_count IS NOT NULL AND processed_count=candidate_count AND failure_count=0)),
    CHECK(status<>'PARTIAL_FAILURE' OR (failure_count>0 AND processed_count>failure_count))
);
CREATE INDEX idx_closure_runs_recent ON order_change_closure_runs(started_at DESC,id);
CREATE INDEX idx_closure_runs_unfinished ON order_change_closure_runs(heartbeat_at,id) WHERE status='RUNNING';

CREATE TABLE order_change_closure_attempts (
    id UUID PRIMARY KEY,
    operation_id UUID NOT NULL,
    order_id BIGINT NOT NULL,
    new_payment_id BIGINT,
    run_id UUID REFERENCES order_change_closure_runs(id) ON DELETE RESTRICT,
    trigger_kind VARCHAR(24) NOT NULL CHECK(trigger_kind IN ('WEBHOOK','SCHEDULER','ADMIN','RECOVERY')),
    context_digest BYTEA NOT NULL CHECK(octet_length(context_digest)=32),
    status VARCHAR(16) NOT NULL CHECK(status IN ('STARTED','COMPLETED','UNKNOWN')),
    result_code VARCHAR(32) CHECK(result_code IN ('CLOSED_RECORDED','ALREADY_CLOSED','NOT_CLOSED','RETRY_LATER','MANUAL_REVIEW_REQUIRED','CONFLICT','NOT_APPLICABLE')),
    reason_code VARCHAR(64) CHECK(reason_code COLLATE "C" ~ '^[A-Z][A-Z0-9_]{0,63}$'),
    version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    FOREIGN KEY(operation_id,order_id) REFERENCES order_change_operations(id,order_id) ON DELETE RESTRICT,
    FOREIGN KEY(order_id,new_payment_id) REFERENCES payments(order_id,id) ON DELETE RESTRICT,
    FOREIGN KEY(operation_id,order_id,new_payment_id) REFERENCES order_change_operations(id,order_id,new_payment_id) ON DELETE RESTRICT,
    CHECK((status='STARTED' AND finished_at IS NULL AND result_code IS NULL AND reason_code IS NULL)
       OR (status='COMPLETED' AND finished_at IS NOT NULL AND result_code IS NOT NULL)
       OR (status='UNKNOWN' AND finished_at IS NOT NULL AND result_code IS NULL AND reason_code IS NOT NULL)),
    CHECK(finished_at IS NULL OR finished_at>=started_at)
);
CREATE INDEX idx_closure_attempts_operation ON order_change_closure_attempts(operation_id,started_at DESC,id);
CREATE INDEX idx_closure_attempts_unfinished ON order_change_closure_attempts(started_at,id) WHERE status='STARTED';

CREATE TABLE order_change_closure_issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_type VARCHAR(16) NOT NULL CHECK(subject_type IN ('OPERATION','SCHEDULER','SYSTEM')),
    subject_key VARCHAR(100) COLLATE "C" NOT NULL,
    operation_id UUID,
    order_id BIGINT,
    new_payment_id BIGINT,
    anomaly_type VARCHAR(64) COLLATE "C" NOT NULL CHECK(anomaly_type ~ '^[A-Z][A-Z0-9_]{0,63}$'),
    severity VARCHAR(16) NOT NULL CHECK(severity IN ('INFO','WARNING','HIGH','CRITICAL')),
    status VARCHAR(16) NOT NULL CHECK(status IN ('OPEN','RESOLVED')),
    episode_no BIGINT NOT NULL CHECK(episode_no>0),
    detection_count BIGINT NOT NULL CHECK(detection_count>0),
    first_detected_at TIMESTAMPTZ NOT NULL,
    last_detected_at TIMESTAMPTZ NOT NULL,
    last_attempt_id UUID REFERENCES order_change_closure_attempts(id) ON DELETE RESTRICT,
    acknowledged_at TIMESTAMPTZ,
    acknowledged_by BIGINT CHECK(acknowledged_by>0),
    assignee_id BIGINT CHECK(assignee_id>0),
    version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
    resolved_at TIMESTAMPTZ,
    resolution_reason VARCHAR(64) CHECK(resolution_reason COLLATE "C" ~ '^[A-Z][A-Z0-9_]{0,63}$'),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    UNIQUE(subject_type,subject_key,anomaly_type),
    FOREIGN KEY(operation_id,order_id) REFERENCES order_change_operations(id,order_id) ON DELETE RESTRICT,
    FOREIGN KEY(order_id,new_payment_id) REFERENCES payments(order_id,id) ON DELETE RESTRICT,
    FOREIGN KEY(operation_id,order_id,new_payment_id) REFERENCES order_change_operations(id,order_id,new_payment_id) ON DELETE RESTRICT,
    CHECK((subject_type='OPERATION' AND operation_id IS NOT NULL AND order_id IS NOT NULL AND subject_key='OP:'||operation_id::TEXT)
       OR (subject_type IN ('SCHEDULER','SYSTEM') AND operation_id IS NULL AND order_id IS NULL AND new_payment_id IS NULL
           AND subject_key COLLATE "C" ~ ('^'||subject_type||':[A-Z][A-Z0-9_]{0,63}$'))),
    CHECK((acknowledged_at IS NULL)=(acknowledged_by IS NULL)),
    CHECK(last_detected_at>=first_detected_at AND updated_at>=created_at),
    CHECK(acknowledged_at IS NULL OR acknowledged_at>=first_detected_at),
    CHECK((status='OPEN' AND resolved_at IS NULL AND resolution_reason IS NULL)
       OR (status='RESOLVED' AND resolved_at IS NOT NULL AND resolution_reason IS NOT NULL AND resolved_at>=last_detected_at))
);
CREATE INDEX idx_closure_issues_open ON order_change_closure_issues(severity,last_detected_at,id) WHERE status='OPEN';
CREATE INDEX idx_closure_issues_age ON order_change_closure_issues(first_detected_at,id) WHERE status='OPEN';
CREATE INDEX idx_closure_issues_operation ON order_change_closure_issues(operation_id,id);

CREATE TABLE order_change_closure_issue_events (
    id UUID PRIMARY KEY,
    issue_id BIGINT NOT NULL REFERENCES order_change_closure_issues(id) ON DELETE RESTRICT,
    episode_no BIGINT NOT NULL CHECK(episode_no>0),
    event_kind VARCHAR(24) NOT NULL CHECK(event_kind IN ('DETECTED','REDETECTED','ACKNOWLEDGED','ASSIGNED','NOTE_ADDED','RESOLVED','REOPENED','CORRECTED','RECHECKED')),
    attempt_id UUID REFERENCES order_change_closure_attempts(id) ON DELETE RESTRICT,
    command_id UUID UNIQUE,
    actor_type VARCHAR(16) NOT NULL CHECK(actor_type IN ('SYSTEM','ADMIN')),
    actor_id BIGINT,
    occurred_at TIMESTAMPTZ NOT NULL,
    safe_reason_code VARCHAR(64) CHECK(safe_reason_code COLLATE "C" ~ '^[A-Z][A-Z0-9_]{0,63}$'),
    context_digest BYTEA CHECK(context_digest IS NULL OR octet_length(context_digest)=32),
    comment VARCHAR(1000),
    CHECK((actor_type='SYSTEM' AND actor_id IS NULL) OR (actor_type='ADMIN' AND actor_id>0 AND actor_id IS NOT NULL))
);
-- NULL attempt means an independent command/event, not the same observation. Its UUID remains unique.
CREATE UNIQUE INDEX uq_closure_event_attempt ON order_change_closure_issue_events(issue_id,attempt_id,event_kind) WHERE attempt_id IS NOT NULL;
CREATE INDEX idx_closure_events_issue ON order_change_closure_issue_events(issue_id,occurred_at,id);

CREATE FUNCTION guard_closure_audit_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='DELETE' THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='Closure audit records cannot be deleted'; END IF;
    IF NEW.id IS DISTINCT FROM OLD.id OR NEW.created_at IS DISTINCT FROM OLD.created_at OR NEW.version<>OLD.version+1 THEN
        RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Invalid closure audit identity or version';
    END IF;
    IF TG_TABLE_NAME='order_change_closure_issues' THEN
        IF (NEW.subject_type,NEW.subject_key,NEW.operation_id,NEW.order_id,NEW.new_payment_id,NEW.anomaly_type,NEW.first_detected_at)
            IS DISTINCT FROM (OLD.subject_type,OLD.subject_key,OLD.operation_id,OLD.order_id,OLD.new_payment_id,OLD.anomaly_type,OLD.first_detected_at)
            OR NEW.episode_no<OLD.episode_no OR NEW.detection_count<OLD.detection_count THEN
            RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Closure issue target is immutable';
        END IF;
    ELSIF TG_TABLE_NAME='order_change_closure_attempts' THEN
        IF OLD.status<>'STARTED' OR NEW.status NOT IN ('COMPLETED','UNKNOWN') OR (NEW.operation_id,NEW.order_id,NEW.new_payment_id,NEW.run_id,NEW.trigger_kind,NEW.context_digest,NEW.started_at)
            IS DISTINCT FROM (OLD.operation_id,OLD.order_id,OLD.new_payment_id,OLD.run_id,OLD.trigger_kind,OLD.context_digest,OLD.started_at) THEN
            RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Closure attempt is final or target changed';
        END IF;
    ELSE
        IF OLD.status<>'RUNNING' OR (NEW.run_kind,NEW.started_at,NEW.enabled_snapshot) IS DISTINCT FROM (OLD.run_kind,OLD.started_at,OLD.enabled_snapshot)
            OR NEW.heartbeat_at<OLD.heartbeat_at OR NEW.processed_count<OLD.processed_count THEN
            RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Closure run is final or regressed';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER closure_issue_update_guard BEFORE UPDATE OR DELETE ON order_change_closure_issues FOR EACH ROW EXECUTE FUNCTION guard_closure_audit_update();
CREATE TRIGGER closure_attempt_update_guard BEFORE UPDATE OR DELETE ON order_change_closure_attempts FOR EACH ROW EXECUTE FUNCTION guard_closure_audit_update();
CREATE TRIGGER closure_run_update_guard BEFORE UPDATE OR DELETE ON order_change_closure_runs FOR EACH ROW EXECUTE FUNCTION guard_closure_audit_update();

-- Parent target columns are immutable. No trigger acquires upper Order/operation/Payment locks.
CREATE FUNCTION check_closure_audit_attempt_owner() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE issue order_change_closure_issues%ROWTYPE; attempt order_change_closure_attempts%ROWTYPE;
BEGIN
    IF TG_TABLE_NAME='order_change_closure_issue_events' THEN SELECT * INTO STRICT issue FROM order_change_closure_issues WHERE id=NEW.issue_id;
    ELSE issue:=NEW; END IF;
    IF TG_TABLE_NAME='order_change_closure_issue_events' THEN SELECT * INTO STRICT attempt FROM order_change_closure_attempts WHERE id=NEW.attempt_id;
    ELSE SELECT * INTO STRICT attempt FROM order_change_closure_attempts WHERE id=NEW.last_attempt_id; END IF;
    IF issue.subject_type<>'OPERATION' OR (issue.operation_id,issue.order_id,issue.new_payment_id) IS DISTINCT FROM (attempt.operation_id,attempt.order_id,attempt.new_payment_id) THEN
        RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Closure audit attempt owner mismatch';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER closure_issue_attempt_owner BEFORE INSERT OR UPDATE ON order_change_closure_issues FOR EACH ROW WHEN (NEW.last_attempt_id IS NOT NULL) EXECUTE FUNCTION check_closure_audit_attempt_owner();
CREATE TRIGGER closure_event_attempt_owner BEFORE INSERT ON order_change_closure_issue_events FOR EACH ROW WHEN (NEW.attempt_id IS NOT NULL) EXECUTE FUNCTION check_closure_audit_attempt_owner();

CREATE FUNCTION reject_closure_audit_removal() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='Closure audit history is append only'; END;
$$;
CREATE TRIGGER closure_events_no_mutation BEFORE UPDATE OR DELETE OR TRUNCATE ON order_change_closure_issue_events FOR EACH STATEMENT EXECUTE FUNCTION reject_closure_audit_removal();
CREATE TRIGGER closure_issues_no_truncate BEFORE TRUNCATE ON order_change_closure_issues FOR EACH STATEMENT EXECUTE FUNCTION reject_closure_audit_removal();
CREATE TRIGGER closure_attempts_no_truncate BEFORE TRUNCATE ON order_change_closure_attempts FOR EACH STATEMENT EXECUTE FUNCTION reject_closure_audit_removal();
CREATE TRIGGER closure_runs_no_truncate BEFORE TRUNCATE ON order_change_closure_runs FOR EACH STATEMENT EXECUTE FUNCTION reject_closure_audit_removal();
REVOKE UPDATE,DELETE,TRUNCATE ON order_change_closure_issue_events FROM PUBLIC;
